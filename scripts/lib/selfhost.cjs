const fs = require('node:fs');
const path = require('node:path');
const net = require('node:net');
const { randomBytes } = require('node:crypto');

function validName(value) {
  if (typeof value !== 'string' || !/^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/.test(value) || value.length > 32) {
    throw new Error('名称须为 1–32 个小写字母、数字和短横线，且以字母开头。');
  }
  return value;
}

function profile(root, instance = 'default') {
  validName(instance);
  const project = instance === 'default' ? 'hapla' : `hapla-${instance}`;
  const directory = path.join(root, '.runtime', 'selfhost', instance);
  return { root, instance, project, directory,
    envFile: instance === 'default' ? path.join(root, '.env.selfhost') : path.join(directory, '.env'),
  };
}

// Read values, never execute a shell or expand shell/Compose variable references.
function parseEnv(source) {
  const result = {};
  for (const line of source.split(/\r?\n/)) {
    if (!line.trim() || line.trimStart().startsWith('#')) continue;
    const match = /^\s*([A-Z_][A-Z0-9_]*)\s*=\s*(.*?)\s*$/.exec(line);
    if (!match) throw new Error('环境文件格式无效：请使用 KEY=value。');
    if (/^(COMPOSE_|DOCKER_)/.test(match[1])) throw new Error('应用配置文件只接受应用变量，请在 Docker 客户端中设置 Compose 和 Docker 选项。');
    let value = match[2];
    if (value.startsWith("'")) {
      const quoted = /^'((?:\\'|[^'])*)'\s*(?:#.*)?$/.exec(value);
      if (!quoted) throw new Error(`环境文件的 ${match[1]} 引号未正确闭合。`);
      value = quoted[1].replace(/\\'/g, "'");
    } else if (value.startsWith('"')) {
      try { value = JSON.parse(value); } catch { throw new Error(`环境文件的 ${match[1]} 引号无效。`); }
    } else value = value.replace(/\s+#.*$/, '').trim();
    if (value.includes('${') || /[\r\n\0]/.test(value)) throw new Error(`请为 ${match[1]} 填写单行实际值，不使用变量引用。`);
    result[match[1]] = value;
  }
  return result;
}

function readConfig(file) {
  const info = fs.lstatSync(file, { throwIfNoEntry: false });
  if (!info) return {};
  if (!info.isFile()) throw new Error('配置必须是普通文件，不能是符号链接。');
  return parseEnv(fs.readFileSync(file, 'utf8'));
}

function writeConfig(file, config) {
  const existed = fs.lstatSync(file, { throwIfNoEntry: false });
  if (existed && !existed.isFile()) throw new Error('拒绝覆盖符号链接或非普通配置文件。');
  const content = '# Generated by Hapla setup. Keep private; retain the master secret with backups.\n'
    + Object.entries(config).map(([key, value]) => {
      if (!/^[A-Z_][A-Z0-9_]*$/.test(key) || /[\r\n\0]/.test(String(value))) throw new Error('配置包含无效键或多行值。');
      return `${key}='${String(value).replace(/'/g, "\\'")}'`;
    }).join('\n') + '\n';
  fs.mkdirSync(path.dirname(file), { recursive: true, mode: 0o700 });
  if (fs.existsSync(file) && fs.readFileSync(file, 'utf8') === content) {
    fs.chmodSync(file, 0o600);
    return;
  }
  const temporary = `${file}.${randomBytes(8).toString('hex')}.tmp`;
  try {
    fs.writeFileSync(temporary, content, { mode: 0o600, flag: 'wx' });
    if (existed) fs.renameSync(temporary, file);
    else {
      // Exclusive creation prevents two first-time setups choosing different keys
      // and overwriting one another before either deployment starts.
      try { fs.linkSync(temporary, file); }
      catch (error) {
        if (error.code === 'EEXIST') throw new Error('另一个配置进程已创建此文件，请重新运行以保留其密钥。');
        throw error;
      }
    }
  } finally { fs.rmSync(temporary, { force: true }); }
}

function validateUrl(value, key, originOnly = false) {
  let url;
  try { url = new URL(value); } catch { throw new Error(`${key} 必须是有效的 HTTP(S) 地址。`); }
  if (!['http:', 'https:'].includes(url.protocol) || url.username || url.password || url.search || url.hash
      || (originOnly && url.pathname !== '/')) throw new Error(`${key} 不支持凭据、查询参数或无效路径。`);
  return value;
}

function validateConfig(config, { template = false } = {}) {
  const port = Number(config.HAPLA_PORT);
  if (!Number.isInteger(port) || port < 1 || port > 65535 || port === 9980) throw new Error('HAPLA_PORT 须为 1–65535 的端口，9980 保留。');
  if (net.isIP(config.HAPLA_BIND_ADDRESS) !== 4) throw new Error('HAPLA_BIND_ADDRESS 须为 IPv4 地址，例如 127.0.0.1 或 0.0.0.0。');
  if (config.HAPLA_DOCKER_SUBNET) {
    const [address, prefix, extra] = config.HAPLA_DOCKER_SUBNET.split('/');
    const [a, b] = address.split('.').map(Number);
    const privateAddress = a === 10 || (a === 172 && b >= 16 && b <= 31) || (a === 192 && b === 168);
    const minPrefix = a === 10 ? 8 : a === 172 ? 12 : 16;
    if (extra !== undefined || net.isIP(address) !== 4 || !privateAddress || !/^\d{1,2}$/.test(prefix)
        || Number(prefix) < minPrefix || Number(prefix) > 29) {
      throw new Error('HAPLA_DOCKER_SUBNET 须为可容纳服务的私有 IPv4 CIDR，例如 10.251.33.0/24。');
    }
  }
  if (!template && (!config.HAPLA_MASTER_SECRET || config.HAPLA_MASTER_SECRET.length < 32
      || /replace-with|your-persistent-local-secret/.test(config.HAPLA_MASTER_SECRET))) {
    throw new Error('HAPLA_MASTER_SECRET 仍是示例或不足 32 字符。已有数据时请恢复原密钥，不要重新生成。');
  }
  validateUrl(config.HAPLA_WEBAPP_URL, 'HAPLA_WEBAPP_URL', true);
  if (config.HAPLA_PREVIEW_HOST_TEMPLATE) {
    const value = config.HAPLA_PREVIEW_HOST_TEMPLATE;
    const hostname = value.replace('{handle}', 'a'.repeat(32));
    if (value.split('{handle}').length !== 2 || hostname.length > 253 || hostname.split('.').length < 2
        || !hostname.split('.').every(label => /^[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?$/i.test(label))) {
      throw new Error('HAPLA_PREVIEW_HOST_TEMPLATE 须为含一个 {handle} 的独立主机名，例如 {handle}.preview.example.com。');
    }
  }
  for (const key of ['PUBLIC_URL', 'HAPLA_ASR_URL', 'HAPLA_R2_CACHE_URL']) if (config[key]) validateUrl(config[key], key);
  if (config.HAPLA_ASR_PAGE_URL) {
    validateUrl(config.HAPLA_ASR_PAGE_URL, 'HAPLA_ASR_PAGE_URL');
    if (!config.HAPLA_ASR_PAGE_URL.startsWith('https://')) throw new Error('听写页面必须使用 HTTPS。');
  }
  if (config.HAPLA_ACCESS_PASSWORD_HASH && !/^scrypt\$[a-f0-9]{32}\$[a-f0-9]{64}$/.test(config.HAPLA_ACCESS_PASSWORD_HASH)) {
    throw new Error('入口密码须为 scrypt 哈希；请使用 --password-file 指定私有密码文件。');
  }
  for (const [key, name] of [['HAPLA_SERVER_IMAGE', 'hapla-server'], ['HAPLA_WEB_IMAGE', 'hapla-web']]) {
    if (config[key] && !new RegExp(`^${name}:[a-zA-Z0-9_.-]+$`).test(config[key])) throw new Error(`${key} 必须使用本项目的镜像名和标签。`);
  }
}

function defaults(selected, existing, options = {}) {
  const config = { PUBLIC_URL: '', HAPLA_ACCESS_PASSWORD_HASH: '', HAPLA_ASR_URL: '', HAPLA_ASR_PAGE_URL: '',
    HAPLA_R2_CACHE_URL: '', HAPLA_BIND_ADDRESS: '127.0.0.1', HAPLA_PORT: '12345', ...existing };
  // Never rotate an existing secret, including a weak/example one: validation
  // explains how to handle it instead of invalidating an existing database.
  if (!Object.hasOwn(existing, 'HAPLA_MASTER_SECRET')) config.HAPLA_MASTER_SECRET = randomBytes(32).toString('hex');
  for (const [key, option] of Object.entries({ HAPLA_PORT: 'port', HAPLA_BIND_ADDRESS: 'bind', HAPLA_WEBAPP_URL: 'url',
    HAPLA_ASR_URL: 'asr-url', HAPLA_ASR_PAGE_URL: 'asr-page-url', HAPLA_R2_CACHE_URL: 'file-service',
    HAPLA_DOCKER_SUBNET: 'subnet' })) {
    if (options[option] !== undefined) config[key] = String(options[option]);
  }
  config.HAPLA_WEBAPP_URL ||= `http://localhost:${config.HAPLA_PORT}`;
  if (options.port !== undefined && options.url === undefined
      && existing.HAPLA_WEBAPP_URL === `http://localhost:${existing.HAPLA_PORT}`) {
    config.HAPLA_WEBAPP_URL = `http://localhost:${config.HAPLA_PORT}`;
  }
  const tag = selected.instance === 'default' ? 'lite' : `instance-${selected.instance}`;
  config.HAPLA_SERVER_IMAGE ||= `hapla-server:${tag}`;
  config.HAPLA_WEB_IMAGE ||= `hapla-web:${tag}`;
  return config;
}

function composeArgs(selected, config) {
  const args = ['compose', '--project-name', selected.project, '--env-file', selected.envFile,
    '-f', path.join(selected.root, 'docker-compose.selfhost.yml')];
  if (config.HAPLA_R2_CACHE_URL) args.push('-f', path.join(selected.root, 'deploy/hapla-cloud-files.override.yml'));
  if (config.HAPLA_DOCKER_SUBNET) args.push('-f', path.join(selected.root, 'deploy/compose.subnet.yml'));
  return args;
}

function allowedOverrides(root) {
  return ['deploy/hapla-cloud-files.override.yml', 'deploy/compose.subnet.yml'].map((file) => path.join(root, file));
}

function ownershipProblems(project, primaryFile, allowedFiles, containers) {
  const managedFiles = new Set([primaryFile, ...allowedFiles]);
  const problems = new Set();
  for (const container of containers) {
    if (container.project !== project) continue;
    const files = container.files.split(',');
    if (!files.includes(primaryFile)) {
      problems.add(`项目 ${project} 已由其他部署配置使用，请选择 --instance 新名称或使用其原配置。`);
    } else if (files.some((file) => !managedFiles.has(file))) {
      problems.add(`项目 ${project} 使用额外的 Compose 覆盖文件，请用原完整文件列表维护，避免丢失挂载。`);
    }
  }
  return [...problems];
}

function isolationProblems(selected, config, containers) {
  const problems = ownershipProblems(selected.project, path.join(selected.root, 'docker-compose.selfhost.yml'),
    allowedOverrides(selected.root), containers);
  for (const container of containers) {
    if (container.name === `${selected.project}-server-1` || container.name === `${selected.project}-web-1`) {
      if (container.project !== selected.project) problems.push(`容器 ${container.name} 不属于目标 Compose 项目，请选择 --instance 新名称。`);
    }
    // Stopped rollback containers and optional workers are not port owners.
    if (container.running && container.project !== selected.project
        && container.ports.includes(String(config.HAPLA_PORT))) {
      problems.push(`端口 ${config.HAPLA_PORT} 正由 ${container.name} 使用，请选择 --port 其他端口。`);
    }
  }
  return [...new Set(problems)];
}

function portAvailable(port, host) {
  return new Promise((resolve) => {
    const server = net.createServer();
    server.once('error', () => resolve(false));
    server.listen({ port: Number(port), host, exclusive: true }, () => server.close(() => resolve(true)));
  });
}

async function freePort(start, host) {
  for (let port = Number(start); port < Math.min(Number(start) + 100, 65536); port++) {
    if (port !== 9980 && await portAvailable(port, host)) return String(port);
  }
  throw new Error('没有找到可用端口，请用 --port 显式指定。');
}

module.exports = { profile, validName, parseEnv, readConfig, writeConfig, validateConfig, defaults,
  composeArgs, allowedOverrides, ownershipProblems, isolationProblems, portAvailable, freePort, validateUrl };
